// Раскладка по физическим клавишам (если на внешней клавиатуре включена латиница).
const ROW_CODES = [
  ['KeyQ', 'KeyW', 'KeyE', 'KeyR', 'KeyT', 'KeyY', 'KeyU', 'KeyI', 'KeyO', 'KeyP', 'BracketLeft', 'BracketRight'],
  ['KeyA', 'KeyS', 'KeyD', 'KeyF', 'KeyG', 'KeyH', 'KeyJ', 'KeyK', 'KeyL', 'Semicolon', 'Quote'],
  ['KeyZ', 'KeyX', 'KeyC', 'KeyV', 'KeyB', 'KeyN', 'KeyM', 'Comma', 'Period'],
];
export function letterFromCode(lang, code) {
  const rows = KEYBOARDS[lang];
  for (let r = 0; r < 3; r++) {
    const i = ROW_CODES[r].indexOf(code);
    if (i >= 0) {
      if (lang === 'uk' && r === 2) return rows[2][i + 1] || null; // Ґ стоит первой экранной клавишей
      return rows[r][i] || null;
    }
  }
  if (lang === 'uk' && code === 'Backquote') return 'Ґ';
  return null;
}

